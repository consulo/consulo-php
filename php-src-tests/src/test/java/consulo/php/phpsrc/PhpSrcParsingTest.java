/**
 * Parses every {@code .phpt} test copied from php-src into {@code src/test/resources/php-src} (refresh with {@code sync-php-src.sh}).
 * <p>
 * A test passes when the PSI text round-trips and the parser reports errors exactly when PHP does ({@code Parse error:}).
 * Current failures are tracked in {@code known-failures.txt}: a new failure or a known failure that now passes fails the build.
 * Every run writes the actual failure list to {@code target/php-src-failures.txt} - copy it over to update the baseline.
 *
 * @author VISTALL
 * @since 2026-10-25
 */
@ExtendWith(ConsuloProjectLoader.class)
public class PhpSrcParsingTest {
    public record Context(PsiFileFactory psiFileFactory) implements InjectingRecord {
    }

    private static final String[] CORPUS_DIRS = {"Zend/tests", "tests"};

    private static final String KNOWN_FAILURES = "/consulo/php/phpsrc/known-failures.txt";

    private static final Set<String> ourActualFailures = Collections.synchronizedSet(new TreeSet<>());

    @TestFactory
    public Stream<DynamicNode> phpSrc(Context context) throws IOException, URISyntaxException {
        URL license = PhpSrcParsingTest.class.getResource("/php-src/LICENSE");
        Assertions.assertNotNull(license, "php-src tests not found in test resources");
        Path root = Paths.get(license.toURI()).getParent();

        Set<String> knownFailures = loadKnownFailures();
        Set<String> debugFiles = loadDebugFiles();

        Map<String, List<Path>> byDirectory = new TreeMap<>();
        for (String corpusDir : CORPUS_DIRS) {
            try (Stream<Path> files = Files.walk(root.resolve(corpusDir))) {
                files.filter(it -> it.toString().endsWith(".phpt"))
                    .sorted()
                    .forEach(it -> byDirectory.computeIfAbsent(root.relativize(it.getParent()).toString(), k -> new ArrayList<>()).add(it));
            }
        }

        return byDirectory.entrySet().stream().map(entry -> DynamicContainer.dynamicContainer(entry.getKey(),
            entry.getValue().stream().map(file -> DynamicTest.dynamicTest(file.getFileName().toString(), file.toUri(),
                () -> doTest(context, root, file, knownFailures, debugFiles)))));
    }

    @AfterAll
    public static void writeActualFailures() throws IOException {
        Path target = Paths.get("target");
        if (Files.isDirectory(target)) {
            List<String> lines = new ArrayList<>();
            lines.add("# generated by PhpSrcParsingTest - copy to src/test/resources" + KNOWN_FAILURES);
            lines.addAll(ourActualFailures);
            Files.write(target.resolve("php-src-failures.txt"), lines, StandardCharsets.UTF_8);
        }
    }

    private static void doTest(Context context, Path root, Path path, Set<String> knownFailures, Set<String> debugFiles) throws IOException {
        PhptFile phpt = PhptFile.load(root, path);
        String source = phpt.source();
        Assumptions.assumeTrue(source != null, "no inline --FILE-- section");

        String problem = checkParsing(context, phpt, source, debugFiles.contains(phpt.relativePath()));
        String relativePath = phpt.relativePath();
        if (problem != null) {
            ourActualFailures.add(relativePath);
        }

        boolean known = knownFailures.contains(relativePath);
        if (problem != null && !known) {
            Assertions.fail(relativePath + ": " + problem);
        }
        if (problem == null && known) {
            Assertions.fail("Parses correctly now - remove '" + relativePath + "' from known-failures.txt");
        }
        // known failure, still failing: reported as skipped, so progress stays visible
        Assumptions.assumeTrue(problem == null, () -> "known failure: " + relativePath + ": " + problem);
    }

    private static @Nullable String checkParsing(Context context, PhptFile phpt, String source, boolean dumpTree) throws IOException {
        try {
            return checkParsingImpl(context, phpt, source, dumpTree);
        }
        catch (StackOverflowError e) {
            return "StackOverflowError";
        }
    }

    private static @Nullable String checkParsingImpl(Context context, PhptFile phpt, String source, boolean dumpTree) throws IOException {
        PsiFile file = context.psiFileFactory().createFileFromText(
            phpt.relativePath().replace('/', '_'),
            PhpLanguage.INSTANCE,
            PhpLanguageLevel.HIGHEST,
            source
        );

        if (dumpTree) {
            Path trees = Files.createDirectories(Paths.get("target", "php-src-trees"));
            Files.writeString(trees.resolve(phpt.relativePath().replace('/', '_') + ".txt"), DebugUtil.psiToString(file, false, true));
        }

        if (!source.contentEquals(file.getText())) {
            return "PSI text differs from source";
        }

        // indexing builds stubs from the PSI - must not fail on any tree the parser produces
        try {
            PhpStubElements.FILE.getBuilder().buildStubTree(file);
        }
        catch (RuntimeException e) {
            return "stub building failed: " + e;
        }

        PsiErrorElement firstError = findFirstError(file);
        if (phpt.expectsParseError()) {
            return firstError == null ? "PHP reports a parse error, but the source parsed cleanly" : null;
        }
        if (firstError != null) {
            return position(source, firstError.getTextRange().getStartOffset()) + ": " + firstError.getErrorDescription();
        }
        return null;
    }

    private static @Nullable PsiErrorElement findFirstError(PsiFile file) {
        PsiErrorElement[] result = new PsiErrorElement[1];
        file.accept(new PsiRecursiveElementWalkingVisitor() {
            @Override
            public void visitElement(PsiElement element) {
                if (element instanceof PsiErrorElement error) {
                    result[0] = error;
                    stopWalking();
                    return;
                }
                super.visitElement(element);
            }
        });
        return result[0];
    }

    private static String position(String text, int offset) {
        int line = 1;
        int lineStart = 0;
        for (int i = 0; i < offset && i < text.length(); i++) {
            if (text.charAt(i) == '\n') {
                line++;
                lineStart = i + 1;
            }
        }
        return "line " + line + ", column " + (offset - lineStart + 1);
    }

    /**
     * Development aid: PSI trees of the files listed in {@code target/php-src-debug.txt} are written to {@code target/php-src-trees}
     */
    private static Set<String> loadDebugFiles() throws IOException {
        Path list = Paths.get("target", "php-src-debug.txt");
        if (!Files.isRegularFile(list)) {
            return Set.of();
        }
        Set<String> result = new LinkedHashSet<>();
        for (String line : Files.readAllLines(list, StandardCharsets.UTF_8)) {
            if (!line.isBlank()) {
                result.add(line.trim());
            }
        }
        return result;
    }

    private static Set<String> loadKnownFailures() throws IOException {
        Set<String> result = new LinkedHashSet<>();
        try (InputStream stream = PhpSrcParsingTest.class.getResourceAsStream(KNOWN_FAILURES)) {
            if (stream == null) {
                return result;
            }
            for (String line : new String(stream.readAllBytes(), StandardCharsets.UTF_8).split("\n")) {
                String trimmed = line.trim();
                if (!trimmed.isEmpty() && !trimmed.startsWith("#")) {
                    result.add(trimmed);
                }
            }
        }
        return result;
    }
}
